package publiccli

import (
	"context"
	"encoding/json"
	"fmt"
	"strings"
	"time"

	"github.com/google/uuid"
	"github.com/spf13/cobra"
	"google.golang.org/protobuf/proto"

	kmsv1 "github.com/MotiveIQ/public/platform/kms/api/v1"
)

var kmsControlVerbs = []string{
	"create-key", "describe-key", "list-keys", "update-key-description", "enable-key", "disable-key",
	"rotate-key-on-demand", "enable-key-rotation", "get-key-rotation-status", "schedule-key-deletion", "cancel-key-deletion",
	"put-key-policy", "get-key-policy", "create-alias", "update-alias", "delete-alias", "get-alias", "list-aliases", "get-operation",
}

func kmsMutation(verb string) bool {
	switch verb {
	case "describe-key", "list-keys", "get-key-rotation-status", "get-key-policy", "get-alias", "list-aliases", "get-operation":
		return false
	default:
		return true
	}
}

func kmsNeedsRevision(verb string) bool {
	return kmsMutation(verb) && verb != "create-key" && verb != "create-alias"
}

type kmsControlInput struct {
	key, alias, requestID, description, policy, policyName, keySpec, keyUsage string
	revision                                                                  int64
	rotationDays, deletionDays                                                uint32
	wait                                                                      bool
	pageSize, maxItems                                                        int
	token                                                                     string
	noPaginate                                                                bool
}

func (c *Command) kmsControlCommand(o *kmsOptions, verb string) *cobra.Command {
	q := &kmsControlInput{}
	command := &cobra.Command{Use: verb, Short: map[string]string{
		"create-key":              "Create a symmetric encryption key.",
		"describe-key":            "Show key state, policy readiness, and material version.",
		"list-keys":               "List KMS keys.",
		"update-key-description":  "Change a key's description.",
		"enable-key":              "Enable crypto operations on a key.",
		"disable-key":             "Disable crypto operations on a key.",
		"rotate-key-on-demand":    "Create a new active material version.",
		"enable-key-rotation":     "Set the automatic rotation period (rotation is always configured).",
		"get-key-rotation-status": "Show the automatic rotation schedule.",
		"schedule-key-deletion":   "Disable a key and schedule its destruction.",
		"cancel-key-deletion":     "Cancel deletion and leave the key disabled.",
		"put-key-policy":          "Replace the key's MotiveIQ resource policy.",
		"get-key-policy":          "Show the desired and applied key policies.",
		"create-alias":            "Create an alias pointing to a key.",
		"update-alias":            "Point an existing alias to another key.",
		"delete-alias":            "Remove an alias without deleting its key.",
		"get-alias":               "Show an alias target and revision.",
		"list-aliases":            "List KMS aliases.",
		"get-operation":           "Show a management operation receipt.",
	}[verb], Args: cobra.NoArgs}
	f := command.Flags()
	required := func(name string) { must(command.MarkFlagRequired(name)) }
	if kmsMutation(verb) || verb == "get-operation" {
		f.StringVar(&q.requestID, "request-id", "", "Mutation UUID; generated by default. Preserve it for exact retries.")
	}
	if verb == "get-operation" {
		required("request-id")
	}
	if kmsMutation(verb) {
		f.BoolVar(&q.wait, "wait", false, "Wait for the operation to succeed, up to --timeout.")
	}
	if kmsNeedsRevision(verb) {
		f.Int64Var(&q.revision, "expected-revision", 0, "Accepted revision to change; default reads current metadata. Required with an explicit --request-id.")
	}
	switch verb {
	case "create-key", "list-keys", "list-aliases", "get-operation", "get-alias", "delete-alias":
	case "create-alias", "update-alias":
		f.StringVar(&q.key, "target-key-id", "", "Target key UUID or URN.")
		required("target-key-id")
	default:
		f.StringVar(&q.key, "key-id", "", "Key UUID or URN (describe-key also accepts aliases).")
		required("key-id")
	}
	if strings.HasSuffix(verb, "-alias") {
		f.StringVar(&q.alias, "alias-name", "", "Alias name (alias/name) or MotiveIQ alias URN.")
		required("alias-name")
	}
	switch verb {
	case "create-key", "update-key-description":
		f.StringVar(&q.description, "description", "", "Key description, or file://PATH (up to 1024 UTF-8 bytes).")
		if verb == "update-key-description" {
			required("description")
		}
	}
	if verb == "create-key" {
		f.StringVar(&q.keySpec, "key-spec", "SYMMETRIC_DEFAULT", "Only SYMMETRIC_DEFAULT is supported.")
		f.StringVar(&q.keyUsage, "key-usage", "ENCRYPT_DECRYPT", "Only ENCRYPT_DECRYPT is supported.")
	}
	if verb == "create-key" || verb == "put-key-policy" {
		f.StringVar(&q.policy, "policy", "", "MotiveIQ key-policy JSON or file://PATH; new keys default to a denying policy.")
		if verb == "put-key-policy" {
			required("policy")
		}
	}
	if verb == "put-key-policy" || verb == "get-key-policy" {
		f.StringVar(&q.policyName, "policy-name", "default", "The single key policy is named default.")
	}
	if verb == "create-key" || verb == "enable-key-rotation" {
		f.Uint32Var(&q.rotationDays, "rotation-period-in-days", 90, "Rotation period in days (1–365); automatic rotation cannot be disabled.")
	}
	if verb == "schedule-key-deletion" {
		f.Uint32Var(&q.deletionDays, "pending-window-in-days", 30, "Deletion waiting period (7–30 days).")
	}
	if verb == "list-keys" || verb == "list-aliases" {
		f.IntVar(&q.pageSize, "page-size", 50, "Maximum items per API request (1–200).")
		f.IntVar(&q.maxItems, "max-items", 0, "Maximum total items; default retrieves all pages.")
		f.StringVar(&q.token, "starting-token", "", "Resume from a previous NextToken.")
		f.BoolVar(&q.noPaginate, "no-paginate", false, "Fetch only one API page.")
		command.MarkFlagsMutuallyExclusive("max-items", "no-paginate")
	}
	command.RunE = func(cmd *cobra.Command, _ []string) error {
		endpoint, err := o.validate()
		if err != nil {
			return err
		}
		if q.key != "" {
			q.key, err = kmsKey(q.key, verb == "describe-key")
			if err != nil {
				return err
			}
		} else if f.Lookup("key-id") != nil || f.Lookup("target-key-id") != nil {
			return fmt.Errorf("key ID must not be empty")
		}
		if f.Lookup("alias-name") != nil {
			q.alias, err = kmsAlias(q.alias)
			if err != nil {
				return err
			}
		}
		if f.Lookup("description") != nil {
			q.description, err = kmsText(q.description, "description", 1024)
			if err != nil {
				return err
			}
		}
		if f.Changed("policy") {
			q.policy, err = kmsText(q.policy, "policy", 16*1024)
			if err != nil {
				return err
			}
			if !json.Valid([]byte(q.policy)) || !strings.HasPrefix(strings.TrimSpace(q.policy), "{") {
				return fmt.Errorf("--policy must contain a MotiveIQ JSON policy object")
			}
		}
		if f.Lookup("policy-name") != nil && q.policyName != "default" {
			return fmt.Errorf("--policy-name must be default")
		}
		if verb == "create-key" && (q.keySpec != "SYMMETRIC_DEFAULT" || q.keyUsage != "ENCRYPT_DECRYPT") {
			return fmt.Errorf("only --key-spec SYMMETRIC_DEFAULT and --key-usage ENCRYPT_DECRYPT are supported")
		}
		if f.Lookup("rotation-period-in-days") != nil && (q.rotationDays < 1 || q.rotationDays > 365) {
			return fmt.Errorf("--rotation-period-in-days must be between 1 and 365")
		}
		if verb == "schedule-key-deletion" && (q.deletionDays < 7 || q.deletionDays > 30) {
			return fmt.Errorf("--pending-window-in-days must be between 7 and 30")
		}
		if kmsNeedsRevision(verb) {
			if (f.Changed("expected-revision") && q.revision <= 0) || q.revision < 0 {
				return fmt.Errorf("--expected-revision must be positive")
			}
			if f.Changed("request-id") && !f.Changed("expected-revision") {
				return fmt.Errorf("explicit --request-id requires --expected-revision so retries preserve the exact request")
			}
		}
		if f.Changed("request-id") || verb == "get-operation" {
			if err := kmsRequestID(q.requestID); err != nil {
				return err
			}
		} else if kmsMutation(verb) {
			q.requestID = uuid.NewString()
		}
		if f.Lookup("page-size") != nil {
			if q.pageSize < 1 || q.pageSize > 200 {
				return fmt.Errorf("--page-size must be between 1 and 200")
			}
			if q.maxItems < 0 || (f.Changed("max-items") && q.maxItems == 0) {
				return fmt.Errorf("--max-items must be positive")
			}
		}
		return c.withKMS(cmd.Context(), o, endpoint, func(ctx context.Context, client KMSClient) error {
			if strings.HasPrefix(q.key, kmsAliasPrefix) {
				alias, err := client.GetAlias(ctx, &kmsv1.GetAliasRequest{AliasUrn: q.key})
				if err != nil {
					return err
				}
				q.key = alias.KeyUrn
			}
			if kmsNeedsRevision(verb) && q.revision == 0 {
				if q.alias != "" {
					alias, err := client.GetAlias(ctx, &kmsv1.GetAliasRequest{AliasUrn: q.alias})
					if err != nil {
						return err
					}
					q.revision = alias.Revision
				} else {
					key, err := client.DescribeKey(ctx, &kmsv1.KeyRequest{KeyUrn: q.key})
					if err != nil {
						return err
					}
					q.revision = key.Revision
				}
				if q.revision <= 0 {
					return fmt.Errorf("KMS returned an invalid revision")
				}
			}
			if verb == "list-keys" || verb == "list-aliases" {
				return c.kmsList(ctx, o, client, verb, q)
			}
			response, err := q.call(ctx, client, verb)
			if err != nil && kmsMutation(verb) {
				return fmt.Errorf("%s (request-id %s, expected-revision %d; inspect get-operation before retrying): %w", verb, q.requestID, q.revision, err)
			}
			if err != nil {
				return err
			}
			var waitErr error
			if q.wait {
				response, waitErr = kmsWaitOperation(ctx, client, response.(*kmsv1.Operation))
			}
			if err := c.printKMS(o.outputOptions, verb, kmsResponse(response)); err != nil {
				return err
			}
			return waitErr
		})
	}
	return command
}

func kmsRequestID(value string) error {
	id, err := uuid.Parse(value)
	if err != nil || id == uuid.Nil || id.String() != value {
		return fmt.Errorf("--request-id must be a canonical nonzero UUID")
	}
	return nil
}

func (q *kmsControlInput) call(ctx context.Context, client KMSClient, verb string) (proto.Message, error) {
	key := &kmsv1.KeyRequest{KeyUrn: q.key}
	mutation := &kmsv1.KeyMutationRequest{KeyUrn: q.key, RequestId: q.requestID, ExpectedRevision: q.revision}
	switch verb {
	case "create-key":
		return client.CreateKey(ctx, &kmsv1.CreateKeyRequest{RequestId: q.requestID, Description: q.description, PolicyDocument: q.policy, RotationPolicy: &kmsv1.RotationPolicy{PeriodDays: q.rotationDays}})
	case "describe-key":
		return client.DescribeKey(ctx, key)
	case "update-key-description":
		return client.UpdateKeyDescription(ctx, &kmsv1.UpdateKeyDescriptionRequest{KeyUrn: q.key, RequestId: q.requestID, ExpectedRevision: q.revision, Description: q.description})
	case "enable-key":
		return client.EnableKey(ctx, mutation)
	case "disable-key":
		return client.DisableKey(ctx, mutation)
	case "rotate-key-on-demand":
		return client.RotateKey(ctx, mutation)
	case "enable-key-rotation":
		return client.PutRotationPolicy(ctx, &kmsv1.PutRotationPolicyRequest{KeyUrn: q.key, RequestId: q.requestID, ExpectedRevision: q.revision, RotationPolicy: &kmsv1.RotationPolicy{PeriodDays: q.rotationDays}})
	case "get-key-rotation-status":
		return client.GetRotationPolicy(ctx, key)
	case "schedule-key-deletion":
		return client.ScheduleKeyDeletion(ctx, &kmsv1.ScheduleKeyDeletionRequest{KeyUrn: q.key, RequestId: q.requestID, ExpectedRevision: q.revision, PendingWindowDays: q.deletionDays})
	case "cancel-key-deletion":
		return client.CancelKeyDeletion(ctx, mutation)
	case "put-key-policy":
		return client.PutKeyPolicy(ctx, &kmsv1.PutKeyPolicyRequest{KeyUrn: q.key, RequestId: q.requestID, ExpectedRevision: q.revision, PolicyDocument: q.policy})
	case "get-key-policy":
		return client.GetKeyPolicy(ctx, key)
	case "create-alias":
		return client.CreateAlias(ctx, &kmsv1.CreateAliasRequest{AliasUrn: q.alias, KeyUrn: q.key, RequestId: q.requestID})
	case "update-alias":
		return client.UpdateAlias(ctx, &kmsv1.UpdateAliasRequest{AliasUrn: q.alias, KeyUrn: q.key, RequestId: q.requestID, ExpectedRevision: q.revision})
	case "delete-alias":
		return client.DeleteAlias(ctx, &kmsv1.DeleteAliasRequest{AliasUrn: q.alias, RequestId: q.requestID, ExpectedRevision: q.revision})
	case "get-alias":
		return client.GetAlias(ctx, &kmsv1.GetAliasRequest{AliasUrn: q.alias})
	case "get-operation":
		return client.GetOperation(ctx, &kmsv1.GetOperationRequest{RequestId: q.requestID})
	default:
		return nil, fmt.Errorf("unsupported KMS command")
	}
}

func (c *Command) kmsList(ctx context.Context, o *kmsOptions, client KMSClient, verb string, q *kmsControlInput) error {
	items := []any{}
	token := q.token
	seen := map[string]bool{token: true}
	field := "Keys"
	if verb == "list-aliases" {
		field = "Aliases"
	}
	for {
		size := q.pageSize
		if q.maxItems > 0 {
			size = min(size, q.maxItems-len(items))
		}
		var next string
		if verb == "list-keys" {
			page, err := client.ListKeys(ctx, &kmsv1.ListKeysRequest{PageSize: uint32(size), PageToken: token})
			if err != nil {
				return err
			}
			for _, key := range page.Keys {
				items = append(items, kmsKeyMetadata(key))
			}
			next = page.NextPageToken
		} else {
			page, err := client.ListAliases(ctx, &kmsv1.ListAliasesRequest{PageSize: uint32(size), PageToken: token})
			if err != nil {
				return err
			}
			for _, alias := range page.Aliases {
				items = append(items, kmsAliasMetadata(alias))
			}
			next = page.NextPageToken
		}
		token = next
		if token == "" || q.noPaginate || (q.maxItems > 0 && len(items) >= q.maxItems) {
			break
		}
		if seen[token] {
			return fmt.Errorf("KMS returned a repeated pagination token")
		}
		seen[token] = true
	}
	result := map[string]any{field: items, "Truncated": token != ""}
	if token != "" {
		result["NextToken"] = token
	}
	return c.printKMS(o.outputOptions, verb, result)
}

func kmsWaitOperation(ctx context.Context, client KMSClient, operation *kmsv1.Operation) (*kmsv1.Operation, error) {
	for {
		switch operation.State {
		case kmsv1.OperationState_OPERATION_STATE_SUCCEEDED:
			return operation, nil
		case kmsv1.OperationState_OPERATION_STATE_PENDING:
		default:
			return operation, fmt.Errorf("KMS operation %s ended in %s (%s)", operation.RequestId, operation.State, operation.ErrorCode)
		}
		timer := time.NewTimer(time.Second)
		select {
		case <-ctx.Done():
			timer.Stop()
			return operation, fmt.Errorf("waiting for KMS operation %s: %w (the accepted operation continues)", operation.RequestId, ctx.Err())
		case <-timer.C:
		}
		next, err := client.GetOperation(ctx, &kmsv1.GetOperationRequest{RequestId: operation.RequestId})
		if err != nil {
			return operation, fmt.Errorf("waiting for KMS operation %s: %w", operation.RequestId, err)
		}
		operation = next
	}
}

func (c *Command) kmsWaitCommand(o *kmsOptions) *cobra.Command {
	var id string
	command := &cobra.Command{Use: "operation-succeeded", Short: "Wait for a receipt to reach Succeeded; fail on Failed or Superseded.", Args: cobra.NoArgs}
	command.Flags().StringVar(&id, "request-id", "", "Request ID from a mutation receipt.")
	must(command.MarkFlagRequired("request-id"))
	command.RunE = func(cmd *cobra.Command, _ []string) error {
		endpoint, err := o.validate()
		if err != nil {
			return err
		}
		if err := kmsRequestID(id); err != nil {
			return err
		}
		return c.withKMS(cmd.Context(), o, endpoint, func(ctx context.Context, client KMSClient) error {
			operation, err := client.GetOperation(ctx, &kmsv1.GetOperationRequest{RequestId: id})
			if err != nil {
				return err
			}
			_, err = kmsWaitOperation(ctx, client, operation)
			return err
		})
	}
	return command
}
